// After the recording: webm → mp4, subtitles (.vtt/.srt), present page data, and the test case doc with results.
// Run alone with: npm run demo:finish
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const SCENES = require('./scenes');

const ROOT = path.resolve(__dirname, '../../..');
const RUN_DIR = path.join(ROOT, '_to_delete/e2e-demo');
const PRESENT = path.join(ROOT, 'present');
const QA_DIR = path.join(ROOT, 'qa/demo');
const NAME = 'XFitness-Chatbot_Demo-Video';

const files = dir => fs.existsSync(dir) ? fs.readdirSync(dir, { withFileTypes: true })
  .flatMap(d => d.isDirectory() ? files(path.join(dir, d.name)) : [path.join(dir, d.name)]) : [];
const found = files(RUN_DIR);
const resultsFile = found.find(f => f.endsWith('demo-results.json'));
const video = found.filter(f => f.endsWith('.webm')).sort((a, b) => fs.statSync(b).mtimeMs - fs.statSync(a).mtimeMs)[0];
if (!resultsFile || !video) { console.error(`ไม่พบผลการอัดใน ${RUN_DIR} — รัน npm run demo ก่อน`); process.exit(1); }

const run = JSON.parse(fs.readFileSync(resultsFile, 'utf8'));
const byId = Object.fromEntries(run.results.map(r => [r.id, r]));
const scenes = SCENES.map(s => ({ ...s, ...(byId[s.id] || { start: null, end: null, pass: false, error: 'ไม่ได้รัน' }) }));
fs.mkdirSync(PRESENT, { recursive: true });
fs.mkdirSync(QA_DIR, { recursive: true });

// 1. video, with each scene's voice-over (demo/tts.py) starting at that scene's start
const mp4 = path.join(PRESENT, `${NAME}.mp4`);
const manifestFile = path.join(ROOT, '_to_delete/e2e-demo-audio/manifest.json');
const voice = fs.existsSync(manifestFile) ? JSON.parse(fs.readFileSync(manifestFile, 'utf8')) : {};
const voiced = scenes.filter(s => s.start != null && voice[s.id] && fs.existsSync(voice[s.id].file));
const LEAD = 0.4;                                          // a breath after the caption appears
const audioArgs = voiced.length ? [
  ...voiced.flatMap(s => ['-i', voice[s.id].file]),
  '-filter_complex', voiced.map((s, i) => { const ms = Math.round((s.start + LEAD) * 1000); return `[${i + 1}:a]adelay=${ms}|${ms}[a${i}]`; }).join(';')
    + ';' + voiced.map((_, i) => `[a${i}]`).join('') + `amix=inputs=${voiced.length}:normalize=0[voice]`,
  '-map', '0:v', '-map', '[voice]', '-c:a', 'aac', '-b:a', '128k',
] : [];
execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', video, ...audioArgs, '-c:v', 'libx264', '-crf', '22', '-preset', 'medium',
  '-pix_fmt', 'yuv420p', '-movflags', '+faststart', mp4], { stdio: 'inherit' });
console.log(voiced.length ? `เสียงพากย์ ${voiced.length} ข้อ` : 'ไม่มีเสียงพากย์ (รัน python demo/tts.py ก่อน)');
const duration = Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', mp4]).toString().trim());

// 2. subtitles: one cue per scene, from its start to the next scene's start
const ts = (s, sep) => { const ms = Math.round(s * 1000), h = Math.floor(ms / 3.6e6), m = Math.floor(ms / 6e4) % 60, x = Math.floor(ms / 1000) % 60;
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(x).padStart(2, '0')}${sep}${String(ms % 1000).padStart(3, '0')}`; };
const timed = scenes.filter(s => s.start != null);
const cues = timed.map((s, i) => ({ from: s.start, to: timed[i + 1]?.start ?? duration, text: `${s.title}\n${s.say}` }));
fs.writeFileSync(path.join(PRESENT, `${NAME}.vtt`), 'WEBVTT\n\n' + cues.map(c => `${ts(c.from, '.')} --> ${ts(c.to, '.')}\n${c.text}\n`).join('\n'));
fs.writeFileSync(path.join(PRESENT, `${NAME}.srt`), cues.map((c, i) => `${i + 1}\n${ts(c.from, ',')} --> ${ts(c.to, ',')}\n${c.text}\n`).join('\n'));

// 3. data for present/index.html (a .js file so the page also works when opened straight from disk)
fs.writeFileSync(path.join(PRESENT, 'demo-data.js'), `// generated by x-fitness/e2e/demo/finish.js — do not edit, edit scenes.js and re-run\nwindow.DEMO = ${JSON.stringify(
  { video: `${NAME}.mp4`, duration, ran: run.ran, scenes: scenes.map(({ id, area, page, title, say, start, pass }) => ({ id, area, page, title, say, start, pass })) }, null, 1)};\n`);

// 4. test case doc with this run's results
const cell = s => String(s).replace(/\|/g, '\\|');
const clock = s => s == null ? '-' : `${Math.floor(s / 60)}:${String(Math.floor(s % 60)).padStart(2, '0')}`;
const passed = scenes.filter(s => s.pass).length;
const doc = `# X Fitness Chatbot — ชุดทดสอบสำหรับวิดีโอสาธิต

> สร้างจาก \`x-fitness/e2e/demo/scenes.js\` โดย \`finish.js\` — แก้ขั้นตอนหรือคำบรรยายที่ scenes.js แล้วรัน \`cd x-fitness/e2e && npm run demo\` ใหม่
> Playwright เล่นทุกข้อต่อกันในแท็บเดียวและอัดเป็นวิดีโอ \`present/${NAME}.mp4\` · ดูพร้อมคำบรรยายที่ \`present/index.html\`

**รอบล่าสุด:** ${new Date(run.ran).toLocaleString('th-TH')} · ผ่าน ${passed}/${scenes.length} ข้อ · ความยาววิดีโอ ${clock(duration)} นาที · เลขเรื่องแชตที่ใช้ทดสอบ ${run.ticket || '-'}

ข้อมูลทดสอบ: สมาชิก FN-10003 (เลขท้ายโทร 5531) · หลังบ้านใช้บัญชีทดสอบ admin · ภาพสลิปตัวอย่าง slip_valid

| รหัส | ส่วน | หน้า | ขั้นตอน | ผลที่คาดหวัง | เวลาในวิดีโอ | ผล |
|---|---|---|---|---|---|---|
${scenes.map(s => `| ${s.id} | ${s.area} | ${cell(s.page)} | ${cell(s.steps)} | ${cell(s.expect)} | ${clock(s.start)} | ${s.pass ? 'ผ่าน' : `ไม่ผ่าน: ${cell(s.error)}`} |`).join('\n')}

## คำบรรยาย (อ่านประกอบวิดีโอ)

${scenes.map(s => `**${clock(s.start)} · ${s.title}** — ${s.say}`).join('\n\n')}

## ข้อมูลที่การทดสอบเขียนลงระบบ

DM-10 ส่งสลิป · DM-12 สร้างแชตส่งต่อพนักงาน · DM-15 พนักงานตอบแชต — ล้างได้ที่หลังบ้าน: ปุ่ม "รีเซ็ตข้อมูลทดสอบ" (สถานะและสลิป) และลบแชตทีละเรื่องในกล่องแชต
`;
fs.writeFileSync(path.join(QA_DIR, 'x-fitness-demo-test-cases.md'), doc);
console.log(`✓ ${path.relative(ROOT, mp4)} (${clock(duration)}) · present/index.html · qa/demo/x-fitness-demo-test-cases.md · ผ่าน ${passed}/${scenes.length}`);
